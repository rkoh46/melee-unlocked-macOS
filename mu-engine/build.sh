#!/usr/bin/env bash
# Builds the melee-unlocked engine for macOS on Apple silicon. Run ./fetch.sh first.
#   ./build.sh game      MU's game image (melee_game.so: an AArch64 Linux ELF) with GCC 15.2 in a container
#   ./build.sh runner    the headless macOS arm64 runner (build/mu-engine/out/mu-runner), with the Command Line Tools
#   ./build.sh           both
# Every container has a time limit, a name and no network.
# Adapted from Melee-NX-NetPlay's experiments/native-engine/build.sh (same author, GPL-3.0-or-later).
# SPDX-License-Identifier: GPL-3.0-or-later
set -euo pipefail
here="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd -P)"
repo="$(cd "$here/.." && pwd -P)"
work="$repo/build/mu-engine"; tree="$work/mu"; out="$work/out"; gen="$work/gen"
LINUX_IMG="${MU_LINUX_IMAGE:-mu-arm-gcc15}"
[ -d "$tree/port/linux" ] || { echo "run mu-engine/fetch.sh first" >&2; exit 1; }
mkdir -p "$out" "$gen"
dock() { local limit=$1 image=$2; shift 2
  timeout "$limit" docker run --rm --name "mumac-build-$$-$RANDOM" --network none -v "$repo:/w" -w /w "$image" bash -ec "$*"; }

# Where the console's address space starts in this process: macOS keeps the low 4 GB of an arm64
# process unmapped, so main memory, the image and the locked cache sit at this base plus their console
# address (a multiple of 4 GB: narrowing a pointer to 32 bits still gives the console address). The game
# image and the host are both built with it (mu_disc.h, patches/0010).
HIGH_BASE=0x100000000000ull
# The game image. -ffixed-x18: x18 is the platform register on macOS (the kernel does not keep it for a
# process), so the Linux-compiled image must never use it. GAME_FLAGS are passed to every C and C++ file.
GAME_FLAGS="${MU_GAME_FLAGS:--ffixed-x18 -DMU_HIGH_BASE=$HIGH_BASE}"
build_game() {
  dock 1500 "$LINUX_IMG" '
    b=build/mu-engine/game
    cmake -S build/mu-engine/mu/sourceport/game -B $b -G Ninja -DCMAKE_C_COMPILER=/usr/local/bin/gcc -DCMAKE_CXX_COMPILER=/usr/local/bin/g++ \
      -DCMAKE_BUILD_TYPE=Release -DMELEE_CPU_BASELINE=AVX2 -DYOUGAME_AGENT_TEST_HOOK=OFF -DYOUGAME_RANKED_BRANCH=ON -DMELEE_DOUBLES=OFF \
      "-DCMAKE_C_FLAGS='"$GAME_FLAGS"'" "-DCMAKE_CXX_FLAGS='"$GAME_FLAGS"'" >/dev/null
    cmake --build $b --target melee_game -j "$(nproc)" > $b/build.log 2>&1 || { grep -E "error|FAILED" -A3 $b/build.log | head -30; exit 1; }
    tail -1 $b/build.log
    cp $b/melee_game.so build/mu-engine/out/melee_game.so
    cp $b/melee_game.snapexcl build/mu-engine/out/melee_game.snapexcl
    # The Gecko lists recordings carry (melee-unlocked'"'"'s own generator; replay metadata only).
    python3 build/mu-engine/mu/tools/native_recording_codes.py build/mu-engine/gen/native_recording_codes.h'
  echo "built $out/melee_game.so"
}

# Embedded files: the game image, the input scripts and the reference digests, so that the runner is one file.
generate() {
  [ -f "$out/melee_game.so" ] || { echo "run mu-engine/build.sh game first" >&2; exit 1; }
  rm -rf "$gen/scripts"; mkdir -p "$gen/scripts"
  cp "$tree"/port/scripts/parity_*.txt "$tree"/port/scripts/native_vs_ko.txt "$gen/scripts/"
  python3 -I "$here/scripts/make_vs4_busy.py" "$tree/port/scripts/parity_vs_onett.txt" "$gen/scripts/vs4_busy.txt"
  {
    echo '.section __TEXT,__const'
    echo '.p2align 4'; echo '.globl _mu_embedded_game'; echo '_mu_embedded_game: .incbin "build/mu-engine/out/melee_game.so"'
    echo '.globl _mu_embedded_game_end'; echo '_mu_embedded_game_end:'
    echo '.globl _mu_embedded_snapexcl'; echo '_mu_embedded_snapexcl: .incbin "build/mu-engine/out/melee_game.snapexcl"'
    echo '.globl _mu_embedded_snapexcl_end'; echo '_mu_embedded_snapexcl_end:'
    for f in "$gen"/scripts/*.txt; do n=$(basename "$f" .txt)
      echo ".p2align 3"; echo "_mu_script_$n: .incbin \"build/mu-engine/gen/scripts/$n.txt\""; echo "_mu_script_${n}_end:"
      echo ".globl _mu_script_$n"; echo ".globl _mu_script_${n}_end"
    done
    for f in "$here"/reference/*.csv.gz; do n=$(basename "$f" .csv.gz)
      echo ".p2align 3"; echo "_mu_ref_$n: .incbin \"mu-engine/reference/$n.csv.gz\""; echo "_mu_ref_${n}_end:"
      echo ".globl _mu_ref_$n"; echo ".globl _mu_ref_${n}_end"
    done
  } > "$gen/embedded.S"
  {
    echo '// generated by mu-engine/build.sh'
    echo '#include <cstddef>'; echo '#include <cstdint>'
    echo 'struct EmbeddedFile { const char* name; const uint8_t* begin; const uint8_t* end; };'
    for f in "$gen"/scripts/*.txt; do n=$(basename "$f" .txt); echo "extern \"C\" const uint8_t mu_script_$n[], mu_script_${n}_end[];"; done
    echo 'extern const EmbeddedFile mu_embedded_scripts[] = {'
    for f in "$gen"/scripts/*.txt; do n=$(basename "$f" .txt); echo "  {\"$n\", mu_script_$n, mu_script_${n}_end},"; done
    echo '};'
    echo 'extern const size_t mu_embedded_script_count = sizeof mu_embedded_scripts / sizeof mu_embedded_scripts[0];'
    for f in "$here"/reference/*.csv.gz; do n=$(basename "$f" .csv.gz); echo "extern \"C\" const uint8_t mu_ref_$n[], mu_ref_${n}_end[];"; done
    echo 'extern const EmbeddedFile mu_embedded_references[] = {'
    for f in "$here"/reference/*.csv.gz; do n=$(basename "$f" .csv.gz); echo "  {\"$n\", mu_ref_$n, mu_ref_${n}_end},"; done
    echo '};'
    echo 'extern const size_t mu_embedded_reference_count = sizeof mu_embedded_references / sizeof mu_embedded_references[0];'
  } > "$gen/embedded_tables.cpp"
  python3 -I "$here/tools/gen_api_names.py" "$tree/port/runtime/abi/mu_host.h" "$gen/api_names.cpp"
}

# The headless macOS runner: MU's headless host services (disc, memory card files, timers, audio mixing,
# scripted pads) plus the loader and runner, with the Command Line Tools (CLAUDE.md: unset DEVELOPER_DIR).
M=build/mu-engine/mu
RUNNER_SOURCES="$M/port/linux/host_services.cpp $M/port/linux/input_script.cpp $M/port/runtime/hle/ax_ucode.cpp
  $M/port/runtime/hle/native_savestate.cpp mu-engine/runner/runner_main.cpp mu-engine/runner/mu_elf.cpp mu-engine/runner/rollback.cpp
  mu-engine/runner/net_host.cpp mu-engine/runner/hostprof.cpp
  mu-engine/runner/macos/abi_macos.cpp mu-engine/runner/macos/frontend_hooks_none.cpp build/mu-engine/gen/api_names.cpp build/mu-engine/gen/embedded_tables.cpp"
RUNNER_C="mu-engine/runner/macos/fixedmap_macos.c mu-engine/runner/macos/mu_imports_macos.c mu-engine/runner/macos/dirtytrack_macos.c"
RUNNER_S="mu-engine/runner/macos/mu_linux_varargs.S mu-engine/runner/macos/hostprof_macos.S build/mu-engine/gen/embedded.S"
RUNNER_INC="-Imu-engine/runner -Imu-engine/runner/macos -I$M/port/linux -I$M/port/runtime/abi -I$M/port/runtime/hle -I$M/port/runtime/host
  -I$M/port/runtime/ppc -I$M/port/runtime/gx -I$M/native"
RUNNER_DEF="-DMU_FOREIGN_ELF -DMU_SQUAD=1 -DMELEE_NO_SLIPPI -DMELEE_PORT_VERSION=\"mu-native\" -DMELEE_LINUX_CPU_BASELINE=\"AArch64\"
  -DMU_CARD_SIMPLE_COMMIT -DMU_HIGH_BASE=$HIGH_BASE"
build_runner() {
  generate; net_object
  ( cd "$repo"; unset DEVELOPER_DIR
    o=build/mu-engine/obj-mac; mkdir -p $o; objs=""
    for f in $RUNNER_C; do b=$o/$(basename $f .c).o; clang -arch arm64 -O2 -g -Wall $RUNNER_INC $RUNNER_DEF -c $f -o $b; objs="$objs $b"; done
    for f in $RUNNER_S; do b=$o/$(basename $f .S)_s.o; clang -arch arm64 -c $f -o $b; objs="$objs $b"; done
    for f in $RUNNER_SOURCES; do b=$o/$(basename $f .cpp).o
      clang++ -arch arm64 -O2 -g -std=gnu++17 -Wall -Wno-unused-function -fno-strict-aliasing $RUNNER_INC $RUNNER_DEF -c $f -o $b & done; wait
    for f in $RUNNER_SOURCES; do objs="$objs $o/$(basename $f .cpp).o"; done
    clang++ -arch arm64 $objs build/mu-engine/out/netplay.o -lz -liconv -lcurl -framework Foundation -o build/mu-engine/out/mu-runner )
  echo "built $out/mu-runner"
}

# The netplay object: Melee-NX-NetPlay's Slippi 3.7.0 netplay (mu-engine/net, copied to build/mu-engine/netsrc with its
# patches and the Mac's applied by net_sources.sh: the WebSocket matchmaking queue with STUN, Slippi's HTTP services over the
# system's libcurl), ENet with its changes, the bridge for the engine's own online code (runner/netplay_bridge_mac.cpp) and
# the app's Discord presence (port/runtime/hle/discord_rpc.cpp, slippi_login.cpp: compiled against this repository's own
# headers), linked into one relocatable object in which only netplay_bridge::* stays global: the app's netplay code and
# melee-unlocked's host services share names.
NS=build/mu-engine/netsrc/port/runtime/hle
NET_HLE="$NS/slippi_online.cpp $NS/slippi_net.cpp $NS/slippi_net_diag.cpp $NS/slippi_offline.cpp $NS/slippi_match_quality.cpp
  $NS/slippi_text.cpp $NS/slippi_version.cpp $NS/slippi_matchmaking_ws.cpp $NS/slippi_report.cpp $NS/slippi_http_curl.cpp
  mu-engine/runner/netplay_bridge_mac.cpp"
NET_INC="-Imu-engine/runner -I$NS -Ibuild/mu-engine/netsrc/enet/include -Iport/third_party/enet/include -Iport/runtime/host -Iport/runtime/gx -Iport/runtime/ppc -Iport/runtime
  -Iport/third_party -Iport/third_party/nlohmann/include -Iport/app -Inative"
# The Slippi release this netplay implements (Melee-NX-NetPlay tools/slippi_pin.json).
NET_DEF='-DMU_NET_SERVICES -DSLIPPI_PIN_VERSION=\"3.7.0\" -DSLIPPI_PIN_TAG=\"v3.7.0\" -DSLIPPI_PIN_MATCHMAKING_URL=\"wss://matchmaking.slippi.gg/v1/queue\"'
# melee-unlocked's own peer-to-peer match (runner/p2p_bridge.cpp over its mu_net session; net_sources.sh copies mu_net, Monocypher
# and the Win32 shim into the netplay sources): its own include path, so nothing of the shim reaches the Slippi sources. Its build
# id is melee-unlocked's version, which both sides of a peer-to-peer match compare.
NETROOT=build/mu-engine/netsrc
P2P_INC="-I$NETROOT/win32_shim -I$NETROOT/port/runtime/mu_net -I$NETROOT/port/third_party/monocypher -Imu-engine/runner -Iport/third_party/enet/include"
P2P_CXX="mu-engine/runner/p2p_bridge.cpp $NETROOT/win32_shim/lobby_shim.cpp $NETROOT/port/runtime/mu_net/rollback_session.cpp $NETROOT/port/runtime/mu_net/peer_connector.cpp
  $NETROOT/port/runtime/mu_net/peer_identity.cpp $NETROOT/port/runtime/mu_net/input_transport.cpp $NETROOT/port/runtime/mu_net/session_security.cpp
  $NETROOT/port/runtime/mu_net/result_outbox.cpp $NETROOT/port/runtime/mu_net/session_types.cpp"
P2P_C="$NETROOT/port/third_party/monocypher/monocypher.c $NETROOT/port/third_party/monocypher/monocypher-ed25519.c"
net_object() {
  ( cd "$repo"; unset DEVELOPER_DIR
    bash mu-engine/net_sources.sh build/mu-engine/netsrc > /dev/null
    o=build/mu-engine/obj-net; rm -rf $o; mkdir -p $o
    for f in callbacks compress host list packet unix; do src=port/third_party/enet/$f.c
      clang -arch arm64 -O2 -w -fvisibility=hidden -DHAS_FCNTL=1 -DHAS_POLL=1 -DHAS_INET_PTON=1 -DHAS_INET_NTOP=1 -DHAS_SOCKLEN_T=1 \
        -DHAS_MSGHDR_FLAGS=1 -Ibuild/mu-engine/netsrc/enet/include -Iport/third_party/enet/include -c $src -o $o/enet_$f.o & done
    for f in peer protocol; do
      clang -arch arm64 -O2 -w -fvisibility=hidden -DHAS_FCNTL=1 -DHAS_POLL=1 -DHAS_INET_PTON=1 -DHAS_INET_NTOP=1 -DHAS_SOCKLEN_T=1 \
        -DHAS_MSGHDR_FLAGS=1 -Ibuild/mu-engine/netsrc/enet/include -Iport/third_party/enet/include -c build/mu-engine/netsrc/enet/$f.c -o $o/enet_$f.o & done
    for f in $NET_HLE; do
      eval clang++ -arch arm64 -std=gnu++20 -O2 -g -w -fvisibility=hidden -fvisibility-inlines-hidden $NET_INC $NET_DEF -c $f -o $o/$(basename $f .cpp).o & done
    # The app's Discord presence, against this repository's headers only.
    for f in port/runtime/hle/discord_rpc.cpp port/runtime/hle/slippi_login.cpp; do
      clang++ -arch arm64 -std=gnu++20 -O2 -g -w -fvisibility=hidden -fvisibility-inlines-hidden -Iport/runtime/hle -Iport/runtime/host -Iport/runtime/ppc -Iport/runtime/gx \
        -Iport/runtime -Iport/third_party -Iport/third_party/nlohmann/include -c $f -o $o/app_$(basename $f .cpp).o & done
    clang++ -arch arm64 -std=gnu++20 -O2 -g -w -fobjc-arc -fvisibility=hidden -Iport/runtime/hle -c port/runtime/hle/slippi_http_apple.mm -o $o/app_slippi_http_apple.o &
    p2p_version=$(head -1 build/mu-engine/mu/VERSION | tr -d '\r')
    for f in $P2P_CXX; do
      clang++ -arch arm64 -std=gnu++20 -O2 -g -w -fvisibility=hidden -fvisibility-inlines-hidden $P2P_INC -DMELEE_PORT_VERSION="\"$p2p_version\"" -c $f -o $o/p2p_$(basename $f .cpp).o & done
    for f in $P2P_C; do clang -arch arm64 -O2 -w -fvisibility=hidden -c $f -o $o/p2p_$(basename $f .c).o & done
    wait
    nm -gU $o/netplay_bridge_mac.o $o/p2p_p2p_bridge.o | awk '$3 ~ /netplay_bridge/ {print $3}' | sort -u > $o/exported.txt
    ld -r -arch arm64 -exported_symbols_list $o/exported.txt $o/*.o -o build/mu-engine/out/netplay.o )
  echo "built $out/netplay.o"
}

case "${1:-all}" in
  game) build_game ;;
  runner) build_runner ;;
  net) net_object ;;
  all) build_game; build_runner ;;
  *) echo "usage: build.sh [game|runner]" >&2; exit 2 ;;
esac
